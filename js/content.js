/* CONTENT_DEFAULT + пользовательские правки из eig_content_v1 */
function getContent(){ return deepMerge(CONTENT_DEFAULT, ls.get(K_CONTENT, {})); }
function setContent(obj){ ls.set(K_CONTENT, obj); }
function resetContent(){ ls.del(K_CONTENT); }

/* объект; phrases.*.items — массивы непустых строк */
function validateContent(o){
  if(!o || typeof o!=="object" || Array.isArray(o)) return "Ожидался объект JSON";
  if(o.phrases!==undefined){
    if(typeof o.phrases!=="object" || Array.isArray(o.phrases)) return "Поле phrases должно быть объектом";
    for(const k of Object.keys(o.phrases)){
      const c=o.phrases[k];
      if(!c || typeof c!=="object") return "Категория " + k + " — не объект";
      if(c.items!==undefined){
        if(!Array.isArray(c.items)) return "phrases." + k + ".items — не массив";
        if(c.items.some(s=>typeof s!=="string" || !s.trim())) return "phrases." + k + ".items содержит не строку";
      }
      if(c.emoji!==undefined && !Array.isArray(c.emoji)) return "phrases." + k + ".emoji — не массив";
    }
  }
  if(o.setToasts!==undefined && !Array.isArray(o.setToasts)) return "setToasts — не массив";
  return null;
}

/* {name} → имя из настроек (по умолчанию «бро»), {n} → число */
function applyVars(s, vars){
  const nm=(Settings.get().name||"").trim() || "бро";
  return String(s).replace(/{name}/g, nm).replace(/{n}/g, (vars&&vars.n)!=null ? vars.n : "");
}
function rnd(a){ return a[Math.floor(Math.random()*a.length)]; }
function phrase(cat, vars){
  const c=getContent().phrases[cat] || getContent().phrases.default;
  return applyVars(rnd(c.items), vars);
}
